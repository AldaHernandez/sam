-- Baseline: documents the `watchlist` table as it existed before migrations were
-- introduced. Reconstructed by hand from the app code, so it uses IF NOT EXISTS
-- and is a no-op on the live database.
-- TODO: verify against the real schema with `supabase db pull` (this also
-- captures constraints/indexes, e.g. the unique one add-to-list relies on).
create table if not exists public.watchlist (
  id          bigint generated by default as identity primary key,
  tmdb_id     integer not null,
  type        varchar not null,
  title       text not null,
  year        varchar,
  poster_url  text,
  overview    text,
  watched     boolean,
  created_at  timestamptz
);
